function localeData(locale: LocaleKey) {
  if (locale === 'en') return { names: EN_NAMES, themes: EN_THEMES }
  if (locale === 'zh') return { names: ZH_FULL_NAMES, themes: ZH_THEMES }
  return { names: JA_NAMES, themes: JA_THEMES }
}

function buildHexagram(locale: LocaleKey, index: number): IChingHexagramLocale {
  const { names, themes } = localeData(locale)
  const name = names[index]
  const theme = themes[index]
  if (locale === 'zh') {
    const classic = zhClassics[index]
    return {
      name,
      shortName: ZH_NAMES[index],
      subtitle: theme,
      judgment: classic.gua_ci,
      reflection: ZH_EXPLANATIONS[index],
      lines: classic.yao_ci.slice(0, 6) as [string, string, string, string, string, string],
      commentary: classic.tuan_ci,
      imageText: classic.da_xiang,
      lineCommentaries: classic.xiao_xiang.slice(0, 6) as [string, string, string, string, string, string],
    }
  }
  if (locale === 'ja') {
    return {
      name,
      shortName: name,
      subtitle: theme,
      judgment: `${name}は、${theme}に目を向けるよう静かに促しています。急いで結論を出さなくても大丈夫です。`,
      reflection: `${theme}の中で、もう少し忍耐と正直さを向けられる場所を探してみてください。`,
      lines: [1, 2, 3, 4, 5, 6].map(n => `${name}の第${n}爻：今ここに意識を戻し、小さく整えることを考えてみてください。`) as [string, string, string, string, string, string],
    }
  }
  return {
    name,
    shortName: name,
    subtitle: theme,
    judgment: `${name} invites attention to ${theme}. There is no need to force a conclusion right away.`,
    reflection: `Within ${theme}, you might notice where patience or honesty is asking for a little more room.`,
    lines: [1, 2, 3, 4, 5, 6].map(n => `${name}, line ${n}: return to the present moment and consider one small adjustment.`) as [string, string, string, string, string, string],
  }
}

function buildHexagrams(locale: LocaleKey): Record<HexagramId, IChingHexagramLocale> {
  return Object.fromEntries(IDS.map((id, index) => [id, buildHexagram(locale, index)])) as Record<HexagramId, IChingHexagramLocale>
}

export function buildIChingLocale(locale: LocaleKey): IChingLocale {
  return {
    ...UI[locale],
    hexagrams: buildHexagrams(locale),
  }
}
